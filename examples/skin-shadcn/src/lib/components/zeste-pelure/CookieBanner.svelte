<!--
  Consent banner (shadcn-svelte), "pelure" style — generated by `zeste add --style pelure`.
  Banner in the theme colors (primary), with outlines and offset shadows in `foreground`.
  "Deny all" and "Accept all" deliberately use the same variant (EU consent rules: equal prominence).
-->
<script lang="ts">
	import { ConsentBanner, getZeste } from '@zeste/svelte';
	import type { Messages } from '@zeste/services/i18n/types';
	import { Button } from '#lib/components/ui/button/index.js';

	const zeste = getZeste<Messages>();
	const t = zeste.messages;

	const chunky =
		'border-foreground h-auto rounded-[10px] border-[2.5px] px-[18px] py-2.5 font-bold shadow-[4px_4px_0_var(--foreground)] active:translate-x-[2px] active:translate-y-[2px] active:shadow-[2px_2px_0_var(--foreground)]';
</script>

{#if zeste.needsReload}
	<!-- An already-loaded script was refused: it only really stops on reload. -->
	<div
		role="status"
		class="bg-primary border-foreground fixed top-4 right-4 z-50 rounded-[14px] border-[3px] p-3 shadow-[6px_6px_0_var(--foreground)]"
	>
		<Button variant="secondary" class={chunky} onclick={() => location.reload()}>{t.reload}</Button>
	</div>
{/if}

<ConsentBanner
	aria-label={t.icon}
	class="bg-primary text-primary-foreground border-foreground fixed inset-x-0 bottom-0 z-50 flex flex-wrap items-center gap-x-6 gap-y-3.5 border-t-[3px] px-6 py-5"
>
	<div class="grid min-w-0 flex-[1_1_20rem] gap-1">
		<span class="text-2xl leading-none font-extrabold tracking-tight">{t.icon}</span>
		<p class="text-[15px] font-medium">{t.alertBigPrivacy}</p>
	</div>
	<div class="flex flex-wrap items-center gap-2.5">
		<Button variant="secondary" class={chunky} {@attach zeste.actions.denyAll}>{t.denyAll}</Button>
		<Button variant="secondary" class={chunky} {@attach zeste.actions.acceptAll}>{t.acceptAll}</Button>
		<Button variant="link" class="text-primary-foreground font-bold" {@attach zeste.actions.openPreferences}>
			{t.personalize}
		</Button>
	</div>
</ConsentBanner>
