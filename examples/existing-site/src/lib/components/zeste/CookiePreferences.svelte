<!--
  Consent preferences — generated by `zeste add`, then wired to the site's design system
  (Modal, Toggle, Button). Nothing is pre-checked: a service the user has not chosen is treated as refused.
-->
<script lang="ts">
	import { getZeste } from '@zeste/svelte';
	import type { Messages } from '@zeste/services/i18n/types';
	import Button from '#lib/ui/Button.svelte';
	import Modal from '#lib/ui/Modal.svelte';
	import Toggle from '#lib/ui/Toggle.svelte';

	const zeste = getZeste<Messages>();
	const t = zeste.messages;
</script>

<Modal bind:open={zeste.preferencesOpen} title={t.title} description={t.disclaimer}>
	{#each zeste.categories as category (category.key)}
		<section class="mb-6" aria-labelledby="zeste-category-{category.key}">
			<h3 id="zeste-category-{category.key}" class="font-serif text-lg">
				{t.categories[category.key]?.title ?? category.key}
			</h3>
			<p class="mb-3 text-sm text-emerald-900">{t.categories[category.key]?.details}</p>
			{#each category.services as service (service.key)}
				<Toggle bind:checked={zeste.draft[service.key]} label={service.name} />
			{/each}
		</section>
	{/each}

	{#snippet footer()}
		<Button variant="secondary" {@attach zeste.actions.denyAll}>{t.denyAll}</Button>
		<Button variant="secondary" {@attach zeste.actions.acceptAll}>{t.acceptAll}</Button>
		<Button {@attach zeste.actions.savePreferences}>{t.save}</Button>
	{/snippet}
</Modal>
