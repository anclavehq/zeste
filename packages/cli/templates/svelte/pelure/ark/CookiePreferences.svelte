<script lang="ts">
	import { Dialog, Portal, Switch } from '@ark-ui/svelte';
	import { getZeste } from '@zeste/svelte';
	import type { Messages } from '@zeste/services/i18n/types';
	import './theme.css';

	const zeste = getZeste<Messages>();
	const t = zeste.messages;

	const focus = 'focus-visible:outline-[3px] focus-visible:outline-offset-[3px] focus-visible:outline-(--zeste-ink)';
	const button = `inline-flex items-center justify-center rounded-[10px] border-[2.5px] border-(--zeste-ink) bg-(--zeste-card) px-[18px] py-2.5 text-sm font-bold text-(--zeste-ink) shadow-[4px_4px_0_var(--zeste-ink)] transition-transform active:translate-x-[2px] active:translate-y-[2px] active:shadow-[2px_2px_0_var(--zeste-ink)] ${focus}`;
	const save = `inline-flex items-center justify-center rounded-[10px] border-[2.5px] border-(--zeste-ink) bg-(--zeste-paper) px-[18px] py-2.5 text-sm font-bold text-(--zeste-ink) shadow-[4px_4px_0_var(--zeste-ink)] transition-transform active:translate-x-[2px] active:translate-y-[2px] active:shadow-[2px_2px_0_var(--zeste-ink)] ${focus}`;
</script>

<Dialog.Root bind:open={zeste.preferencesOpen} lazyMount unmountOnExit>
	<Portal>
		<Dialog.Backdrop data-zeste-skin="pelure" class="fixed inset-0 z-50 bg-(--zeste-scrim)" />
		<Dialog.Positioner class="fixed inset-0 z-50 flex items-center justify-center p-4">
		<Dialog.Content
			data-zeste-skin="pelure"
			class="relative grid max-h-[85vh] w-full max-w-lg gap-4 overflow-y-auto rounded-[14px] border-[3px] border-(--zeste-ink) bg-(--zeste-card) p-6 text-(--zeste-ink) shadow-[8px_8px_0_var(--zeste-ink)]"
		>
			<Dialog.Title class="pr-8 text-2xl font-extrabold tracking-tight">{t.title}</Dialog.Title>
			<Dialog.Description class="text-sm leading-relaxed font-medium">{t.disclaimer}</Dialog.Description>

			{#each zeste.categories as category (category.key)}
				<section class="grid gap-2 border-t-[2.5px] border-(--zeste-ink) pt-3" aria-labelledby="zeste-category-{category.key}">
					<h3 id="zeste-category-{category.key}" class="text-sm font-bold">
						{t.categories[category.key]?.title ?? category.key}
					</h3>
					<p class="text-sm">{t.categories[category.key]?.details}</p>
					<ul class="grid gap-3 pt-1">
						{#each category.services as service (service.key)}
							<li class="flex items-center justify-between gap-4">
								<div class="text-sm">
									<span class="font-medium">{service.name}</span>
									{#if service.privacyUrl}
										<a
											href={service.privacyUrl}
											target="_blank"
											rel="noreferrer"
											class="block underline underline-offset-2"
										>
											{t.privacyUrl} <span class="sr-only">{service.name} {t.newWindow}</span>
										</a>
									{/if}
								</div>
								<Switch.Root bind:checked={zeste.draft[service.key]} class="inline-flex items-center">
									<Switch.Control
										class="inline-flex h-[28px] w-12 shrink-0 cursor-pointer items-center rounded-[8px] border-[2.5px] border-(--zeste-ink) bg-white p-[2px] transition data-[state=checked]:bg-(--zeste-paper) data-[focus-visible]:outline-2 data-[focus-visible]:outline-offset-2 data-[focus-visible]:outline-(--zeste-ink)"
									>
										<Switch.Thumb
											class="block size-[18px] rounded-[4px] bg-(--zeste-ink) transition data-[state=checked]:translate-x-[20px]"
										/>
									</Switch.Control>
									<Switch.Label class="sr-only">{service.name}</Switch.Label>
									<!-- Ark exposes a checkbox: announce it as a switch to screen readers -->
									<Switch.HiddenInput role="switch" />
								</Switch.Root>
							</li>
						{/each}
					</ul>
				</section>
			{/each}

			{#if zeste.exempt.length}
				<p class="border-t-[2.5px] border-(--zeste-ink) pt-3 text-sm">
					<span class="font-bold">{t.mandatoryTitle}</span> :
					{zeste.exempt.map((s) => s.name).join(', ')}
				</p>
			{/if}

			<div class="flex flex-wrap items-center gap-2 pt-2">
				<button type="button" class={button} {@attach zeste.actions.denyAll}>{t.denyAll}</button>
				<button type="button" class={button} {@attach zeste.actions.acceptAll}>{t.acceptAll}</button>
				<button type="button" class="{save} ml-auto" {@attach zeste.actions.savePreferences}>{t.save}</button>
			</div>

			<Dialog.CloseTrigger
				class="absolute top-5 right-5 grid size-8 place-items-center rounded-[8px] border-[2.5px] border-(--zeste-ink) bg-(--zeste-paper) font-bold {focus}"
				aria-label={t.close}
			>
				<span aria-hidden="true">✕</span>
			</Dialog.CloseTrigger>
		</Dialog.Content>
		</Dialog.Positioner>
	</Portal>
</Dialog.Root>
