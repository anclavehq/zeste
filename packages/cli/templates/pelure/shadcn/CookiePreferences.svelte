<!--
  Consent preferences (shadcn-svelte), "pelure" style — generated by `zeste add --style pelure`, yours to edit.
  Nothing is pre-checked: a service the user has not chosen is treated as refused.
-->
<script lang="ts">
	import { getZeste } from '@zeste/svelte';
	import type { Messages } from '@zeste/services/i18n/types';
	import { Button } from '%UI%/button/index.js';
	import * as Dialog from '%UI%/dialog/index.js';
	import { Label } from '%UI%/label/index.js';
	import { Switch } from '%UI%/switch/index.js';

	const zeste = getZeste<Messages>();
	const t = zeste.messages;

	const chunky =
		'border-foreground h-auto rounded-[10px] border-[2.5px] px-[18px] py-2.5 font-bold shadow-[4px_4px_0_var(--foreground)] active:translate-x-[2px] active:translate-y-[2px] active:shadow-[2px_2px_0_var(--foreground)]';
</script>

<Dialog.Root bind:open={zeste.preferencesOpen}>
	<Dialog.Content class="border-foreground max-h-[85vh] overflow-y-auto rounded-[14px] border-[3px] shadow-[8px_8px_0_var(--foreground)] ring-0 sm:max-w-lg" showCloseButton={false}>
		<Dialog.Header>
			<Dialog.Title class="text-2xl font-extrabold tracking-tight">{t.title}</Dialog.Title>
			<Dialog.Description>{t.disclaimer}</Dialog.Description>
		</Dialog.Header>

		{#each zeste.categories as category (category.key)}
			<section class="border-foreground grid gap-2 border-t-[2.5px] pt-3" aria-labelledby="zeste-category-{category.key}">
				<h3 id="zeste-category-{category.key}" class="font-bold">
					{t.categories[category.key]?.title ?? category.key}
				</h3>
				<p class="text-muted-foreground">{t.categories[category.key]?.details}</p>
				<ul class="grid gap-3 pt-1">
					{#each category.services as service (service.key)}
						<li class="flex items-center justify-between gap-4">
							<div>
								<Label for="zeste-service-{service.key}">{service.name}</Label>
								{#if service.privacyUrl}
									<a
										href={service.privacyUrl}
										target="_blank"
										rel="noreferrer"
										class="text-muted-foreground hover:text-foreground block underline underline-offset-2"
									>
										{t.privacyUrl} <span class="sr-only">{service.name} {t.newWindow}</span>
									</a>
								{/if}
							</div>
							<Switch id="zeste-service-{service.key}" bind:checked={zeste.draft[service.key]} />
						</li>
					{/each}
				</ul>
			</section>
		{/each}

		{#if zeste.exempt.length}
			<p class="text-muted-foreground border-foreground border-t-[2.5px] pt-3">
				<span class="text-foreground font-medium">{t.mandatoryTitle}</span> :
				{zeste.exempt.map((s) => s.name).join(', ')}
			</p>
		{/if}

		<Dialog.Footer class="sm:justify-start">
			<Button variant="secondary" class={chunky} {@attach zeste.actions.denyAll}>{t.denyAll}</Button>
			<Button variant="secondary" class={chunky} {@attach zeste.actions.acceptAll}>{t.acceptAll}</Button>
			<Button class="{chunky} sm:ml-auto" {@attach zeste.actions.savePreferences}>{t.save}</Button>
		</Dialog.Footer>

		<Dialog.Close class="absolute top-4 right-4" aria-label={t.close}>
			{#snippet child({ props })}
				<Button variant="ghost" size="icon-sm" {...props}><span aria-hidden="true">✕</span></Button>
			{/snippet}
		</Dialog.Close>
	</Dialog.Content>
</Dialog.Root>
